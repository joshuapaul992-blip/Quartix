#!/bin/sh
# Regenerates src/gen/trust_anchors.c from a PEM CA bundle (default: certifi's
# copy of the Mozilla bundle) using BearSSL's own brssl tool built for the host.
set -eu
cd "$(dirname "$0")/.."
BUNDLE=${1:-$(python3 -c 'import certifi; print(certifi.where())')}
VERSION=$(python3 -c 'import certifi; print(certifi.__version__)' 2>/dev/null || echo unknown)
TMP=$(mktemp -d)
trap 'rm -rf "$TMP"' EXIT
cc -O2 -Ithird_party/bearssl/inc -Ithird_party/bearssl/src -o "$TMP/brssl" \
   $(find third_party/bearssl/src third_party/bearssl/tools -name '*.c')
"$TMP/brssl" ta "$BUNDLE" > "$TMP/ta.c"
{
  echo "/* Generated by tools/gen_trust_anchors.sh from the Mozilla CA bundle (certifi $VERSION). Do not edit. */"
  echo '#include "bearssl.h"'
  sed 's/^static const br_x509_trust_anchor TAs/const br_x509_trust_anchor QX_TAs/; s/^#define TAs_NUM   \(.*\)/const size_t QX_TAs_NUM = \1;/' "$TMP/ta.c"
} > src/gen/trust_anchors.c
echo "wrote src/gen/trust_anchors.c"
